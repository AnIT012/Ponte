_WHERE_IS = re.compile(r"^(\w+) is (\{?\w+\}?|\"[^\"]*\")$")
_WHERE_WITHIN = re.compile(r"^(\w+) within (\d+ \w+)$")


def where_to_go(cond: str, fields: dict[str, Field], line: int, var: str = "x") -> tuple[str, set[str]]:
    """where の1行を Go の条件式にする。戻り: (式, 必要な import)"""
    m = _WHERE_IS.match(cond.strip())
    if m:
        fname, value = m.group(1), m.group(2)
        if fname not in fields:
            raise CodegenError(line, f"where: 項目 {fname} がありません")
        f = fields[fname]
        if value.startswith("{") and value.endswith("}"):
            return f"{var}.{go_name(fname)} == {go_lower(value[1:-1])}", set()
        if value.startswith('"'):
            return f"{var}.{go_name(fname)} == {value}", set()
        if f.one_of is not None and value not in f.one_of:
            raise CodegenError(line, f"where: {fname} に {value} という値はありません（{', '.join(f.one_of)}）")
        return f"{var}.{go_name(fname)} == {q(value)}", set()
    m = _WHERE_WITHIN.match(cond.strip())
    if m:
        fname, dur = m.group(1), m.group(2)
        if fname not in fields or fields[fname].go_type != "time.Time":
            raise CodegenError(line, f"where: within は datetime の項目にだけ使えます: '{cond}'")
        try:
            d = go_duration(dur)
        except ValueError:
            raise CodegenError(line, f"where: 期間が読めません: '{dur}'")
        # now <= 値 <= 期限。days / weeks は暦日で数える（仕様の example がそれを前提にしている。QUESTIONS.md Q19）
        n, unit = dur.split()
        if unit.rstrip("s") in ("day", "week"):
            days = int(n) * (7 if unit.startswith("week") else 1)
            end = f"endOfDay(now.AddDate(0, 0, {days}))"
        else:
            end = f"now.Add({d})"
        return f"!{var}.{go_name(fname)}.Before(now) && !{var}.{go_name(fname)}.After({end})", {"time"}
    raise CodegenError(line, f"where の書き方が分かりません（決まっているのは `項目 is 値` と `項目 within 期間`）: '{cond}'")


def list_source_entity(spec: Spec, lst: Node) -> str:
    """list の元をたどって entity 名にする。"""
    seen = set()
    cur = lst
    while True:
        fr = cur.child("from")
        if fr is None:
            raise CodegenError(cur.line, f"list {cur.name}: from がありません")
        src = fr.text.strip()
        if src in seen:
            raise CodegenError(cur.line, f"list {cur.name}: 循環参照")
        seen.add(src)
        nxt = spec.find("list", src)
        if nxt is None:
            return src
        cur = nxt


def gen_lists(spec: Spec, model: Model, package: str) -> str:
    imports = {"sort"}
    body: list[str] = []
    for lst in spec.decls_of("list"):
        ename = list_source_entity(spec, lst)
        if ename not in model.entities:
            raise CodegenError(lst.line, f"list {lst.name}: from の {ename} は entity ではありません")
        E = go_name(ename)
        fields = {f.name: f for f in model.entities[ename]}
        src = lst.child("from").text.strip()
        L = go_name(lst.name)
        body.append(f"// {L} — list {lst.name}")
        body.append(f"// {' / '.join(spec.lines[c.line - 1].strip() for c in lst.children)}")
        body.append(f"func {L}(all []{E}, now time.Time) []{E} {{")
        imports.add("time")
        if src in model.entities:
            body.append("\tsrc := all")
        else:
            body.append(f"\tsrc := {go_name(src)}(all, now)")
        body.append(f"\tout := make([]{E}, 0, len(src))")
        body.append("\tfor _, x := range src {")
        conds = []
        for w in lst.children_of("where"):
            expr, imps = where_to_go(w.text, fields, w.line)
            imports |= imps
            conds.append(expr)
        if conds:
            body.append(f"\t\tif !({' && '.join(f'({c})' for c in conds)}) {{")
            body.append("\t\t\tcontinue")
            body.append("\t\t}")
        body.append("\t\tout = append(out, x)")
        body.append("\t}")
        sb = lst.child("sort by")
        if sb is not None:
            key = sb.text.strip()
            if key not in fields:
                raise CodegenError(sb.line, f"sort by: 項目 {key} がありません")
            K = go_name(key)
            if fields[key].go_type == "time.Time":
                less = f"out[i].{K}.Before(out[j].{K})"
            else:
                less = f"out[i].{K} < out[j].{K}"
            body.append("\tsort.SliceStable(out, func(i, j int) bool { return " + less + " })")
        body.append("\treturn out")
        body.append("}")
        body.append("")
    if body:
        body.append("// endOfDay — その日の 23:59:59.999999999。within N days は暦日で数える。")
        body.append("func endOfDay(t time.Time) time.Time {")
        body.append("\ty, m, d := t.Date()")
