def gen_flows(spec: Spec, model: Model, package: str) -> str:
    o = Out(package)
    for fl in spec.decls_of("flow"):
        ename, fname = flow_target(fl)
        if ename not in model.entities:
            raise CodegenError(fl.line, f"flow {fl.name}: entity {ename} がありません")
        E, F = go_name(ename), go_name(fname)
        states = flow_states(fl)
        edges = flow_transitions(fl)
        conflicts = flow_conflicts(fl)
        o.w(f"// ---- flow {fl.name} ----")
        o.w(f"// {' / '.join(spec.lines[c.line - 1].strip() for c in fl.children)}")
        o.w()
        o.w(f"// {E}{F}Transitions — -> の通りにしか動けない。")
        o.w(f"var {E}{F}Transitions = map[string][]string{{")
        for s in states:
            dsts = [d for (src, d) in edges if src == s]
            items = ", ".join(q(d) for d in dsts)
            o.w(f"\t{q(s)}: {{{items}}},")
        o.w("}")
        o.w()
        o.w(f"// {E}{F}WinsOver — on conflict の勝者。[勝者][敗者] = true")
        o.w(f"var {E}{F}WinsOver = map[string]map[string]bool{{")
        winners: dict[str, list[str]] = {}
        for w, l in conflicts:
            winners.setdefault(w, []).append(l)
        for w in sorted(winners):
            items = ", ".join(f"{q(l)}: true" for l in sorted(winners[w]))
            o.w(f"\t{q(w)}: {{{items}}},")
        o.w("}")
        o.w()
        o.w(f"func {go_lower(ename)}{F}CanMove(from, to string) bool {{")
        o.w(f"\tfor _, d := range {E}{F}Transitions[from] {{")
        o.w("\t\tif d == to {")
        o.w("\t\t\treturn true")
        o.w("\t\t}")
        o.w("\t}")
        o.w("\treturn false")
        o.w("}")
        o.w()
        o.w(f"// Move{F} は {ename}.{fname} を to へ動かす。flow で管理する項目は move でしか変えられない（set 禁止）。")
        o.w("//")
        o.w("// on conflict: 同じ元の状態から分岐した先に、矛盾する move が続けて届いたとき、")
        o.w("//   - 今の状態が to に負けるなら to で上書きする")
        o.w("//   - 今の状態が to に勝つなら何もしない（エラーにもしない）")
        o.w(f"func (b *{E}Box) Move{F}(to string) error {{")
        o.w(f"\treturn b.Update(func(cur *{E}, prev *{E}) error {{")
        o.w(f"\t\tif cur.{F} == to {{")
        o.w("\t\t\treturn nil")
        o.w("\t\t}")
        o.w(f"\t\tif {go_lower(ename)}{F}CanMove(cur.{F}, to) {{")
        o.w("\t\t\t*prev = *cur")
        o.w(f"\t\t\tcur.{F} = to")
        o.w("\t\t\treturn nil")
        o.w("\t\t}")
        o.w(f"\t\t// 矛盾する move: 直前の状態から cur.{F} と to の両方へ行ける")
        o.w(f"\t\tif {go_lower(ename)}{F}CanMove(prev.{F}, to) && {go_lower(ename)}{F}CanMove(prev.{F}, cur.{F}) {{")
        o.w(f"\t\t\tif {E}{F}WinsOver[to][cur.{F}] {{")
        o.w(f"\t\t\t\tcur.{F} = to // prev はそのまま（同じ分岐点からの上書き）")
        o.w("\t\t\t\treturn nil")
        o.w("\t\t\t}")
        o.w(f"\t\t\tif {E}{F}WinsOver[cur.{F}][to] {{")
        o.w("\t\t\t\treturn nil")
        o.w("\t\t\t}")
        o.w("\t\t}")
        o.w(f'\t\treturn fmt.Errorf("{ename}.{fname}: %s から %s へは動けません", cur.{F}, to)')
        o.w("\t})")
        o.w("}")
        o.w()
    return o.text()


