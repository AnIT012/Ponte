_IO = re.compile(r"^(\w+):\s*(.+)$")
_HOW_LIMIT = re.compile(r"^limit (\d+ \w+)$")
_HOW_RETRY = re.compile(r"^on failure retry (\d+) times?$")


@dataclass
class ActionSig:
    name: str
    in_name: str
    in_type: Field
    out_name: str
    out_type: Field
    examples: list[tuple[str, str, int]]
    else_: str
    nevers: list[str]
    by: str
    limit: str | None
    retry: int | None
    how_unknown: list[str]


def read_action(a: Node, model: Model) -> ActionSig:
    inp, out = a.child("input"), a.child("output")
    if inp is None or out is None:
        raise CodegenError(a.line, f"action {a.name}: input と output が要ります")
    mi = _IO.match(inp.text.strip())
    if not mi:
        raise CodegenError(inp.line, f"input は `名前: 型` で書きます: '{inp.text}'")
    mo = _IO.match(out.text.strip())
    if mo:
        out_name, out_type = mo.group(1), mo.group(2)
    else:
        out_name, out_type = "result", out.text.strip()
    examples = []
    for ex in a.children_of("example"):
        if "->" not in ex.text:
            raise CodegenError(ex.line, f"action の example は `入力 -> 出力` で書きます: '{ex.text}'")
        i, o = [s.strip() for s in ex.text.split("->", 1)]
        examples.append((i, o, ex.line))
    limit = retry = None
    unknown = []
    how = a.child("how")
    if how is not None:
        for h in how.children:
            if (m := _HOW_LIMIT.match(h.raw)):
                limit = m.group(1)
            elif (m := _HOW_RETRY.match(h.raw)):
                retry = int(m.group(1))
            else:
                unknown.append(h.raw)
    by = a.child("by").text.strip() if a.child("by") else "ai"
    return ActionSig(
        name=a.name, in_name=mi.group(1), in_type=go_type_of(mi.group(2), model, inp.line),
        out_name=out_name, out_type=go_type_of(out_type, model, out.line),
        examples=examples, else_=a.child("else").text.strip() if a.child("else") else "",
        nevers=[n.text for n in a.children_of("never")], by=by, limit=limit, retry=retry,
        how_unknown=unknown,
    )


def gen_actions(spec: Spec, model: Model, package: str) -> str:
    o = Out(package)
    o.w("// ErrElse — 自信がないとき、中身は必ずこれを返す（else の逃げ道に進む）。")
    o.w('var ErrElse = errors.New("else")')
    o.w()
    o.w("// How — how に書かれた決まりごと。")
    o.w("type How struct {")
    o.w("\tLimit time.Duration // limit N seconds（0 なら無制限）")
    o.w("\tRetry int           // on failure retry N times")
    o.w("}")
    o.w()
    for a in spec.decls_of("action"):
        sig = read_action(a, model)
        A = go_name(sig.name)
        o.w(f"// ---- action {sig.name} ----")
        for n in sig.nevers:
            o.w(f"// never {n}")
        o.w(f"// else {sig.else_}")
        o.w(f"// by {sig.by}")
        o.w()
        o.w(f"// {A} — 契約だけ。中身は by {sig.by} が埋める。example を全部通らないと採用されない。")
        o.w(f"type {A} interface {{")
        o.w(f"\tRun(ctx context.Context, {go_lower(sig.in_name)} {sig.in_type.go_type}) ({go_lower(sig.out_name)} {sig.out_type.go_type}, err error)")
        o.w("}")
        o.w()
        o.w(f"// {A}Impl — 中身。by ai なら AI が、by code なら自分のコードが、by connect なら外部サービスがここに入る。")
        o.w(f"var {A}Impl {A}")
        o.w()
        o.w(f"// {A}Else — 自信がないときの逃げ道（{sig.else_ or '（else 無し）'}）。")
        o.w(f"const {A}Else = {q(sig.else_)}")
        o.w()
        lim = go_duration(sig.limit) if sig.limit else "0"
        o.w(f"var {A}How = How{{Limit: {lim}, Retry: {sig.retry or 0}}}")
        for h in sig.how_unknown:
            o.w(f"// how: {h}（決まった変換が無い。AIに渡す）")
        o.w()
        o.w(f"// Run{A} は how（limit / retry）を守って中身を呼ぶ。")
        o.w(f"func Run{A}(ctx context.Context, {go_lower(sig.in_name)} {sig.in_type.go_type}) ({sig.out_type.go_type}, error) {{")
        o.w(f"\tvar zero {sig.out_type.go_type}")
        o.w(f"\tif {A}Impl == nil {{")
        o.w(f'\t\treturn zero, errors.New("{sig.name}: 中身がまだありません（by {sig.by}）")')
        o.w("\t}")
        o.w("\tvar err error")
        o.w(f"\tfor attempt := 0; attempt <= {A}How.Retry; attempt++ {{")
        o.w("\t\tc, cancel := ctx, func() {}")
        o.w(f"\t\tif {A}How.Limit > 0 {{")
        o.w(f"\t\t\tc, cancel = context.WithTimeout(ctx, {A}How.Limit)")
        o.w("\t\t}")
        o.w(f"\t\tvar out {sig.out_type.go_type}")
        o.w(f"\t\tout, err = {A}Impl.Run(c, {go_lower(sig.in_name)})")
        o.w("\t\tcancel()")
        o.w("\t\tif err == nil {")
        o.w("\t\t\treturn out, nil")
        o.w("\t\t}")
        o.w("\t\tif errors.Is(err, ErrElse) {")
        o.w("\t\t\treturn zero, err // 自信がない → 逃げ道へ。retry はしない")
        o.w("\t\t}")
        o.w("\t}")
        o.w("\treturn zero, err")
        o.w("}")
        o.w()
    return o.text()


def go_literal(value: str, f: Field, line: int) -> tuple[str, set[str]]:
    """example の値を Go の式にする。"""
    v = value.strip()
    if f.go_type == "string" or f.go_type in {go_name(t) for t in []}:
        s = v[1:-1] if v.startswith('"') and v.endswith('"') else v
        return q(s), set()
    if f.go_type == "float64":
        return v, set()
    if f.go_type == "time.Time":
        s = v[1:-1] if v.startswith('"') and v.endswith('"') else v
        return f"specTime({q(s)})", set()
    if f.go_type == "time.Duration":
        return go_duration(v), {"time"}
    # 未定義の型（Message など）は text 扱い
    s = v[1:-1] if v.startswith('"') and v.endswith('"') else v
    return f"{f.go_type}({q(s)})", set()


