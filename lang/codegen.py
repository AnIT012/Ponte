_SAYS = re.compile(r'^user says "(.*)"$')
_NOTIFY_EACH = re.compile(r"^notify user each of (\w+)$")
_NOTIFY_TEXT = re.compile(r'^notify user "(.*)"$')
_TIME_EVERY = re.compile(r"^every (\w+) at (\d{1,2}:\d{2})$")
_DATA = re.compile(r"^(\w+) (is created|moves to \w+|is removed)$")


def says_pattern_to_regexp(pattern: str) -> tuple[str, list[str]]:
    """`submitted {company}` → (`^submitted (?P<company>.+)$`, ["company"])"""
    names: list[str] = []
    out = "^"
    pos = 0
    for m in re.finditer(r"\{(\w+)\}", pattern):
        out += re.escape(pattern[pos:m.start()])
        out += f"(?P<{m.group(1)}>.+)"
        names.append(m.group(1))
        pos = m.end()
    out += re.escape(pattern[pos:]) + "$"
    return out, names


def gen_rules(spec: Spec, model: Model, package: str) -> str:
    imports = {"time"}
    body: list[str] = []
    body.append("// Effects — ルールが外に向かってやること。中身はアプリ側が用意する。")
    body.append("type Effects interface {")
    body.append("\t// Notify はユーザーに通知する。item は通知の対象（entity の値か文字列）。")
    body.append("\tNotify(rule string, item any)")
    body.append("}")
    body.append("")
    body.append("// Schedule — 時間の出来事。")
    body.append("type Schedule struct {")
    body.append("\tEvery string // day / monday / ...")
    body.append("\tAt    string // 21:00")
    body.append("}")
    body.append("")

    for r in spec.decls_of("rule"):
        R = go_name(r.name)
        when = r.child("when")
        do = r.child("do")
        because = r.child("because")
        if when is None or do is None:
            raise CodegenError(r.line, f"rule {r.name}: when と do が要ります")
        kind = classify_when(when.text)
        body.append(f"// ---- rule {r.name} ----")
        if because is not None:
            body.append(f"// because {because.text}")
        body.append(f"// when {when.text}")
        body.append(f"// do {do.text}")
        body.append("")

        # when の形ごとに関数の入口を決める
        params = ["s *Store", "fx Effects", "now time.Time"]
        extra_vars: list[str] = []
        if kind == "time":
            m = _TIME_EVERY.match(when.text.strip())
            if m:
                body.append(f"// {R}Schedule — いつ動かすか。")
                body.append(f"var {R}Schedule = Schedule{{Every: {q(m.group(1))}, At: {q(m.group(2))}}}")
                body.append("")
        elif kind == "user":
            m = _SAYS.match(when.text.strip())
            if m:
                rx, names = says_pattern_to_regexp(m.group(1))
                imports.add("regexp")
                body.append(f"var {go_lower(r.name)}Pattern = regexp.MustCompile({q(rx)})")
                body.append("")
                sig = ", ".join(f"{go_lower(n)} string" for n in names)
                body.append(f"// Match{R} — user says の文からルールの入力を取り出す。")
                body.append(f"func Match{R}(text string) ({sig + ', ' if sig else ''}ok bool) {{")
                body.append(f"\tm := {go_lower(r.name)}Pattern.FindStringSubmatch(text)")
                body.append("\tif m == nil {")
                body.append("\t\treturn")
                body.append("\t}")
                for i, n in enumerate(names):
                    body.append(f"\t{go_lower(n)} = m[{i + 1}]")
                body.append("\tok = true")
                body.append("\treturn")
                body.append("}")
                body.append("")
                extra_vars = names
                params += [f"{go_lower(n)} string" for n in names]
            else:
                # user does 〇〇: 入力は無し
                pass
        elif kind == "data":
            m = _DATA.match(when.text.strip())
            ename = m.group(1)
            if ename not in model.entities:
                raise CodegenError(when.line, f"rule {r.name}: {ename} は entity ではありません")
            params.append(f"target *{go_name(ename)}Box")
        elif kind == "external":
            raise CodegenError(when.line, f"rule {r.name}: connect からの出来事は △（設計は次回）なので変換できません: '{when.text}'")

        body.append(f"// Rule{R} — 出来事が起きたら呼ぶ。中で対象の箱ごとに並列に動く。")
        body.append(f"func Rule{R}({', '.join(params)}) error {{")
        body += _gen_do(spec, model, r, do, extra_vars)
        body.append("}")
        body.append("")

    o = Out(package)
    for l in body:
        o.w(l)
    return o.text()


def _gen_do(spec: Spec, model: Model, r: Node, do: Node, vars_: list[str]) -> list[str]:
    text = do.text.strip()
    lines: list[str] = []
    m = _NOTIFY_EACH.match(text)
    if m:
        lname = m.group(1)
        lst = spec.find("list", lname)
        if lst is None:
            raise CodegenError(do.line, f"rule {r.name}: list {lname} がありません")
        ename = list_source_entity(spec, lst)
        E = go_name(ename)
        lines.append(f"\tfor _, item := range {go_name(lname)}(s.All{E}s(), now) {{")
        lines.append(f"\t\tfx.Notify({q(r.name)}, item)")
        lines.append("\t}")
        lines.append("\treturn nil")
        return lines
    m = _NOTIFY_TEXT.match(text)
    if m:
        lines.append(f"\tfx.Notify({q(r.name)}, {q(m.group(1))})")
        lines.append("\treturn nil")
        return lines
    mv = parse_move(text)
    if mv:
        ename = mv["target"]
        if ename not in model.entities:
            raise CodegenError(do.line, f"rule {r.name}: {ename} は entity ではありません")
        E = go_name(ename)
        fields = {f.name: f for f in model.entities[ename]}
        flows = [f for f in spec.decls_of("flow") if flow_target(f)[0] == ename]
        state_fields = [f for f in fields.values() if f.one_of and mv["state"] in f.one_of]
        if not state_fields:
            raise CodegenError(do.line, f"rule {r.name}: {ename} に {mv['state']} という状態はありません")
        F = go_name(state_fields[0].name)
        if not any(flow_target(f)[1] == state_fields[0].name for f in flows):
            raise CodegenError(do.line, f"rule {r.name}: {ename}.{state_fields[0].name} に flow がありません（move は flow で管理する項目にだけ使えます）")
        cond, _ = where_to_go(mv["where"], fields, do.line, var="cur")
        lines.append("\tvar firstErr error")
        lines.append("\tvar mu sync.Mutex")
        lines.append(f"\ts.Each{E}Parallel(func(b *{E}Box) {{")
        lines.append("\t\tcur := b.Get()")
        lines.append(f"\t\tif !({cond}) {{")
        lines.append("\t\t\treturn")
        lines.append("\t\t}")
        lines.append(f"\t\tif err := b.Move{F}({q(mv['state'])}); err != nil {{")
        lines.append("\t\t\tmu.Lock()")
        lines.append("\t\t\tif firstErr == nil {")
        lines.append("\t\t\t\tfirstErr = err")
        lines.append("\t\t\t}")
        lines.append("\t\t\tmu.Unlock()")
        lines.append("\t\t}")
        lines.append("\t})")
        lines.append("\treturn firstErr")
        return lines
    raise CodegenError(do.line, f"rule {r.name}: do の書き方が分かりません（決まっているのは notify user each of 〇〇 / notify user \"...\" / move 箱 where 条件 to 状態）: '{text}'")



