def gen_entities(spec: Spec, model: Model, package: str) -> str:
    o = Out(package)
    o.w("// ---- 型 ----")
    o.w()
    for t in model.opaque_types:
        o.w(f"// {t} は仕様の中で定義されていない型（connect が持ってくる想定）。text として扱う。QUESTIONS.md Q3")
        o.w(f"type {go_name(t)} string")
        o.w()
    for ename in model.entity_order:
        E = go_name(ename)
        o.w(f"// {E} — entity {ename}")
        o.w(f"type {E} struct {{")
        o.w(f"\tID string")
        for f in model.entities[ename]:
            comment = f"// {f.spec_type}"
            o.w(f"\t{go_name(f.name)} {f.go_type} {comment}")
        o.w("}")
        o.w()
        for f in model.entities[ename]:
            if f.one_of:
                o.w(f"// {E}.{go_name(f.name)} の取りうる値")
                o.w("const (")
                for v in f.one_of:
                    o.w(f"\t{E}{go_name(f.name)}{go_name(v)} = {q(v)}")
                o.w(")")
                o.w()
        o.w(f"// {E}Box — entity {ename} の1件＝1つの箱。")
        o.w("// 箱への書き換えは受信 channel を1つの goroutine が順に処理する（同じ箱の中は1つずつ）。")
        o.w(f"type {E}Box struct {{")
        o.w(f"\tinbox chan {go_lower(ename)}Msg")
        o.w(f"\tstate {E}")
        o.w(f"\tprev  {E} // 直前の状態（on conflict の判定に使う）")
        o.w("}")
        o.w()
        o.w(f"type {go_lower(ename)}Msg struct {{")
        o.w(f"\tapply func(cur *{E}, prev *{E}) error // prev は状態を進めるときに apply が書き換える")
        o.w(f"\tread  func(cur {E})")
        o.w("\tdone  chan error")
        o.w("}")
        o.w()
        o.w(f"// New{E}Box は箱を作って goroutine を起動する。")
        o.w(f"func New{E}Box(v {E}) *{E}Box {{")
        o.w(f"\tb := &{E}Box{{inbox: make(chan {go_lower(ename)}Msg), state: v, prev: v}}")
        o.w("\tgo b.loop()")
        o.w("\treturn b")
        o.w("}")
        o.w()
        o.w(f"func (b *{E}Box) loop() {{")
        o.w("\tfor m := range b.inbox {")
        o.w("\t\tif m.read != nil {")
        o.w("\t\t\tm.read(b.state)")
        o.w("\t\t\tm.done <- nil")
        o.w("\t\t\tcontinue")
        o.w("\t\t}")
        o.w("\t\tnext := b.state")
        o.w("\t\tprev := b.prev")
        o.w("\t\terr := m.apply(&next, &prev)")
        o.w("\t\tif err == nil {")
        o.w("\t\t\tb.state = next")
        o.w("\t\t\tb.prev = prev")
        o.w("\t\t}")
        o.w("\t\tm.done <- err")
        o.w("\t}")
        o.w("}")
        o.w()
        o.w(f"// Update は箱の中身を書き換える。順番に1つずつ処理される。")
        o.w(f"func (b *{E}Box) Update(fn func(cur *{E}, prev *{E}) error) error {{")
        o.w(f"\tm := {go_lower(ename)}Msg{{apply: fn, done: make(chan error, 1)}}")
        o.w("\tb.inbox <- m")
        o.w("\treturn <-m.done")
        o.w("}")
        o.w()
        o.w(f"// Get は箱の中身のコピーを返す。")
        o.w(f"func (b *{E}Box) Get() {E} {{")
        o.w(f"\tvar out {E}")
        o.w(f"\tm := {go_lower(ename)}Msg{{read: func(cur {E}) {{ out = cur }}, done: make(chan error, 1)}}")
        o.w("\tb.inbox <- m")
        o.w("\t<-m.done")
        o.w("\treturn out")
        o.w("}")
        o.w()
        o.w(f"// Close は箱の goroutine を止める。")
        o.w(f"func (b *{E}Box) Close() {{ close(b.inbox) }}")
        o.w()

    # Store: 箱の集まり。箱をまたぐ処理は並列（ルールは箱ごとに goroutine で走る）
    o.w("// Store — 箱の集まり。箱をまたぐ処理は並列に走る（EachParallel）。")
    o.w("type Store struct {")
    o.w("\tmu sync.RWMutex")
    for ename in model.entity_order:
        o.w(f"\t{go_name(ename)}s []*{go_name(ename)}Box")
    o.w("}")
    o.w()
    o.w("func NewStore() *Store { return &Store{} }")
    o.w()
    for ename in model.entity_order:
        E = go_name(ename)
        o.w(f"// Add{E} は新しい箱を作って Store に入れる。")
        o.w(f"func (s *Store) Add{E}(v {E}) *{E}Box {{")
        o.w(f"\tb := New{E}Box(v)")
        o.w("\ts.mu.Lock()")
        o.w(f"\ts.{E}s = append(s.{E}s, b)")
        o.w("\ts.mu.Unlock()")
        o.w("\treturn b")
        o.w("}")
        o.w()
        o.w(f"// All{E}s は今の中身のスナップショット（読むだけ）。")
        o.w(f"func (s *Store) All{E}s() []{E} {{")
        o.w("\ts.mu.RLock()")
        o.w(f"\tboxes := append([]*{E}Box(nil), s.{E}s...)")
        o.w("\ts.mu.RUnlock()")
        o.w(f"\tout := make([]{E}, 0, len(boxes))")
        o.w("\tfor _, b := range boxes {")
        o.w("\t\tout = append(out, b.Get())")
        o.w("\t}")
        o.w("\treturn out")
        o.w("}")
        o.w()
        o.w(f"// Each{E}Parallel は箱ごとに並列で fn を走らせ、全部終わるのを待つ。箱をまたぐ処理は並列が標準。")
        o.w(f"func (s *Store) Each{E}Parallel(fn func(b *{E}Box)) {{")
        o.w("\ts.mu.RLock()")
        o.w(f"\tboxes := append([]*{E}Box(nil), s.{E}s...)")
        o.w("\ts.mu.RUnlock()")
        o.w("\tvar wg sync.WaitGroup")
        o.w("\tfor _, b := range boxes {")
        o.w("\t\twg.Add(1)")
        o.w(f"\t\tgo func(b *{E}Box) {{")
        o.w("\t\t\tdefer wg.Done()")
        o.w("\t\t\tfn(b)")
        o.w("\t\t}(b)")
        o.w("\t}")
        o.w("\twg.Wait()")
        o.w("}")
        o.w()
        o.w(f"// Close は全部の箱を止める。")
    o.w("func (s *Store) Close() {")
    o.w("\ts.mu.Lock()")
    o.w("\tdefer s.mu.Unlock()")
    for ename in model.entity_order:
        E = go_name(ename)
        o.w(f"\tfor _, b := range s.{E}s {{")
        o.w("\t\tb.Close()")
        o.w("\t}")
    o.w("}")
    return o.text()


