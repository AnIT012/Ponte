def go_name(name: str) -> str:
    """owner → Owner, due_soon → DueSoon, Application → Application"""
    parts = re.split(r"[_\-\s]+", name)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def go_lower(name: str) -> str:
    n = go_name(name)
    return n[:1].lower() + n[1:]


BUILTIN_TYPES = {
    "text": "string",
    "number": "float64",
    "datetime": "time.Time",
    "duration": "time.Duration",
}

_DURATION = re.compile(r"^(\d+)\s+(seconds?|minutes?|hours?|days?|weeks?)$")


def go_duration(text: str) -> str:
    """`3 days` → `3 * 24 * time.Hour`"""
    m = _DURATION.match(text.strip())
    if not m:
        raise ValueError(text)
    n, unit = m.group(1), m.group(2).rstrip("s")
    return {
        "second": f"{n} * time.Second",
        "minute": f"{n} * time.Minute",
        "hour": f"{n} * time.Hour",
        "day": f"{n} * 24 * time.Hour",
        "week": f"{n} * 7 * 24 * time.Hour",
    }[unit]


@dataclass
class Field:
    name: str
    spec_type: str
    go_type: str
    line: int
    one_of: list[str] | None = None
    ref: str | None = None


@dataclass
class Model:
    """spec から codegen に必要なものだけ取り出した形。"""
    entities: dict[str, list[Field]] = field(default_factory=dict)
    entity_order: list[str] = field(default_factory=list)
    opaque_types: list[str] = field(default_factory=list)  # Message など未定義の型名


def go_type_of(spec_type: str, model: Model, line: int) -> Field:
    t = spec_type.strip()
    if t in BUILTIN_TYPES:
        return Field("", t, BUILTIN_TYPES[t], line)
    vals = one_of_values(t)
    if vals is not None:
        return Field("", t, "string", line, one_of=vals)
    if t.startswith("ref "):
        target = t[4:].strip()
        return Field("", t, "string", line, ref=target)
    if t.startswith("many "):
        target = t[5:].strip()
        return Field("", t, "[]string", line, ref=target)
    if t in model.entities:
        return Field("", t, go_name(t), line)
    if re.fullmatch(r"[A-Z]\w*", t):
        # 未定義の型名（connect が持ってくる Message など）。QUESTIONS Q3
        if t not in model.opaque_types:
            model.opaque_types.append(t)
        return Field("", t, go_name(t), line)
    raise CodegenError(line, f"型が分かりません: '{spec_type}'")


def build_model(spec: Spec) -> Model:
    model = Model()
    for e in spec.decls_of("entity"):
        model.entity_order.append(e.name)
        model.entities[e.name] = []
    for e in spec.decls_of("entity"):
        fields = []
        for name, typ, line in entity_fields(e):
            f = go_type_of(typ, model, line)
            f.name = name
            fields.append(f)
        model.entities[e.name] = fields
    return model


