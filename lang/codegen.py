def gen_matches(spec: Spec, model: Model, package: str) -> str:
    o = Out(package)
    for m in spec.decls_of("match"):
        words = m.text.split()
        if len(words) != 3 or words[1] != "to" or "." not in words[0]:
            raise CodegenError(m.line, f"match は `match 箱.項目 to 名前` で書きます: '{m.raw}'")
        ename, fname = words[0].split(".", 1)
        target = words[2]
        if ename not in model.entities:
            raise CodegenError(m.line, f"match: entity {ename} がありません")
        fields = {f.name: f for f in model.entities[ename]}
        if fname not in fields:
            raise CodegenError(m.line, f"match: 項目 {fname} がありません")
        F = go_name(ename) + go_name(fname) + "To" + go_name(target)
        o.w(f"// {F} — match {m.text}。結果は text 扱い（QUESTIONS.md Q6）")
        o.w(f"func {F}(v string) string {{")
        o.w("\tswitch v {")
        otherwise = None
        for arm in m.children:
            if arm.keyword == "otherwise":
                otherwise = arm.text.split("->", 1)[1].strip()
                continue
            if "->" not in arm.raw:
                raise CodegenError(arm.line, f"match の行は `値 -> 結果` で書きます: '{arm.raw}'")
            k, v = [s.strip() for s in arm.raw.split("->", 1)]
            if fields[fname].one_of is not None and k not in fields[fname].one_of:
                raise CodegenError(arm.line, f"match: {fname} に {k} という値はありません")
            o.w(f"\tcase {q(k)}:")
            o.w(f"\t\treturn {q(v)}")
        o.w("\tdefault:")
        o.w(f"\t\treturn {q(otherwise)}")
        o.w("\t}")
        o.w("}")
        o.w()
    return o.text()


