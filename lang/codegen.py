"""フェーズ2：決まった部分の Go 変換（AI無し・毎回同じ結果）。

  entity → struct ＋ 箱（goroutine 1つ＋受信 channel。同じ箱への書き換えは1つずつ）
  flow   → 遷移表 ＋ Move（-> の通りにしか動けない）＋ on conflict の勝者判定
  list   → フィルタ関数（where は全部 and、sort by は昇順）
  match  → 表引き関数（otherwise が default）
  rule   → 出来事ごとのハンドラ（時間／user says／データ）
  action → interface だけ（中身は空）＋ example からテスト
  how    → limit / on failure retry を適用するラッパー

変換できない書き方（仕様に無い／決まっていない）は推測せず CodegenError で止める。
出力は spec の内容だけから決まる（時刻・乱数・辞書の順序に依存しない）。
"""
