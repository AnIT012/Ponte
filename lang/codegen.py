class Out:
    """Go ファイル1つ分。import は本文で使っている標準パッケージから自動で決める。"""

    STD = ("context", "errors", "fmt", "regexp", "sort", "strings", "sync", "testing", "time")

    def __init__(self, package: str, imports: list[str] | None = None):
        self.lines: list[str] = []
        self.package = package

    def w(self, line: str = ""):
        self.lines.append(line)

    def text(self) -> str:
        body = "\n".join(self.lines)
        imports = sorted(p for p in self.STD if re.search(rf"\b{p}\.", body))
        head = [
            "// Code generated by nameless-lang codegen. DO NOT EDIT.",
            "// 仕様(.spec)から AI 無しで決まった変換をしたもの。同じ仕様からは毎回同じ結果になる。",
            "",
            f"package {self.package}",
            "",
        ]
        if imports:
            head.append("import (")
            for imp in imports:
                head.append(f'\t"{imp}"')
            head.append(")")
            head.append("")
        return gofmt("\n".join(head) + "\n" + body.rstrip("\n") + "\n")


def gofmt(text: str) -> str:
    """gofmt があれば整形する（決定的）。無ければそのまま。"""
    import shutil
    import subprocess
    exe = shutil.which("gofmt")
    if not exe:
        return text
    r = subprocess.run([exe], input=text, capture_output=True, text=True)
    if r.returncode != 0:
        raise CodegenError(0, "gofmt が通りません:\n" + r.stderr + "\n" + text)
    return r.stdout


def q(s: str) -> str:
    """Go の文字列リテラル"""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


