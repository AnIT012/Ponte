BY_CODE = {e[0]: e for e in ERRORS}


def explain(code: str) -> str | None:
    e = BY_CODE.get(code.upper())
    if e is None:
        return None
    c, title, why, fix = e
    return f"{c}  {title}\n\nなぜ止めるか: {why}\nどう直すか:   {fix}"


def errors_table() -> str:
    rows = ["| コード | 何が起きたか | なぜ止めるか | どう直すか |", "|---|---|---|---|"]
    esc = lambda x: x.replace("|", "\\|")            # 表の中の | は区切りにしない
    rows += [f"| {c} | {esc(t)} | {esc(w)} | {esc(f)} |" for c, t, w, f in ERRORS]
    return "\n".join(rows)
